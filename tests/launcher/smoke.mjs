import { _electron as electron, expect } from '@playwright/test';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';

const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'portal-desktop-'));
const source = path.join(temp, 'Offline game.html');
await fs.writeFile(source, '<h1>Offline game works</h1><script>document.body.dataset.node=typeof require; document.body.dataset.ipc=typeof window.launcher;document.body.dataset.previous=localStorage.getItem("save")||"empty";localStorage.setItem("save","retained");fetch("https://example.com/blocked").then(()=>document.body.dataset.network="allowed",()=>document.body.dataset.network="blocked");</script>');
let app;
const launchOptions = { args: [...(process.platform === 'linux' ? ['--no-sandbox', '--ozone-platform=headless'] : []), '--user-data-dir=' + path.join(temp, 'settings'), path.resolve('.')], env: { ...process.env, XDG_CACHE_HOME: process.env.XDG_CACHE_HOME || path.join(temp, 'cache') }, timeout: 30000 };
try {
  app = await electron.launch(launchOptions);
  let page = await app.firstWindow();
  await page.setViewportSize({ width: 1160, height: 800 });
  await expect(page.getByRole('heading', { name: /マイライブラリ/ })).toBeVisible();
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  await expect(page.getByRole('button', { name: '＋ ゲームを取り込む' })).toBeDisabled();
  await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, temp);
  await page.getByRole('button', { name: 'フォルダーを選択', exact: true }).click();
  await expect(page.locator('#folder')).toHaveText(temp);
  await app.evaluate(({ dialog }, filename) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] }); }, source);
  await page.getByRole('button', { name: '＋ ゲームを取り込む' }).click();
  await expect(page.getByRole('heading', { name: 'Offline game', exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: path.join(os.tmpdir(), 'portal-launcher.png') });
  await page.locator('#search').fill('missing'); await expect(page.locator('.card')).toHaveCount(0);
  await page.locator('#search').fill('offline'); await expect(page.locator('.card')).toHaveCount(1);
  const nextWindow = app.waitForEvent('window');
  await page.getByRole('button', { name: 'プレイ', exact: true }).click();
  const game = await nextWindow;
  await game.setViewportSize({ width: 1100, height: 760 });
  await expect(game.getByRole('heading', { name: 'Offline game works' })).toBeVisible();
  await expect(game.locator('body')).toHaveAttribute('data-node', 'undefined');
  await expect(game.locator('body')).toHaveAttribute('data-ipc', 'undefined');
  await expect(game.locator('body')).toHaveAttribute('data-network', 'blocked');
  await expect(game.locator('body')).toHaveAttribute('data-previous', 'empty');
  assert.equal(await game.evaluate(() => localStorage.getItem('save')), 'retained');
  await app.evaluate(({ BrowserWindow }) => { const game = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().startsWith('gameportal:')); game.close(); });
  await page.reload(); await expect(page.locator('.card')).toHaveCount(1);
  const reopened = app.waitForEvent('window'); await page.getByRole('button', { name: 'プレイ', exact: true }).click();
  const gameAgain = await reopened; await gameAgain.setViewportSize({ width: 1100, height: 760 }); await expect(gameAgain.getByRole('heading', { name: 'Offline game works' })).toBeVisible();
  await expect(gameAgain.locator('body')).toHaveAttribute('data-previous', 'retained');
  assert.equal(await gameAgain.evaluate(() => localStorage.getItem('save')), 'retained');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().startsWith('gameportal:')).close());
  await app.close(); app = await electron.launch(launchOptions); page = await app.firstWindow();
  await page.setViewportSize({ width: 1160, height: 800 });
  await expect(page.locator('#folder')).toHaveText(temp);
  await expect(page.locator('.card')).toHaveCount(1);
  const restoredWindow = app.waitForEvent('window'); await page.getByRole('button', { name: 'プレイ', exact: true }).click();
  const restoredGame = await restoredWindow;
  await expect(restoredGame.locator('body')).toHaveAttribute('data-previous', 'retained');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().startsWith('gameportal:')).close());
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }); });
  await page.getByRole('button', { name: 'Offline gameを削除' }).click(); await expect(page.locator('.card')).toHaveCount(0);
  assert.ok(await fs.stat(source));
  console.log('Electron smoke passed: folder selection, import, search, offline play, network denial, isolated games, reopen and deletion.');
} finally { if (app) await app.close(); await fs.rm(temp, { recursive: true, force: true }); }
